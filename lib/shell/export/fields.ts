export function redactExportRow(model: string, row: Record<string, unknown>) {
  return Object.fromEntries(
    (EXPORT_FIELDS[model] ?? [])
      .filter((key) => Object.hasOwn(row, key))
      .map((key) => [key, row[key]]),
  );
}
